def find_repo_root(start: Path | None = None) -> Path:
    """Find the repository root from a notebook or script working directory."""
    start = Path.cwd() if start is None else Path(start)
    for path in [start, *start.parents]:
        if (path / "pipeline" / "config").exists():
            return path
    raise FileNotFoundError("Could not find repository root containing pipeline/config.")


def load_spatial_split_assignments(assignments_csv: str | Path) -> pd.DataFrame:
    """Load row-level split assignments generated by spatial_test_set_selection.ipynb."""
    assignments = read_csv_robust(assignments_csv)
    required = {"ID_norm", "split_role", "cv_fold", "split_label"}
    missing = required - set(assignments.columns)
    if missing:
        raise ValueError(f"Spatial split assignments are missing columns: {sorted(missing)}")

    assignments = assignments.copy()
    assignments["ID_norm"] = normalize_id(assignments["ID_norm"])
    assignments["split_role"] = assignments["split_role"].astype(str).str.strip()
    assignments["split_label"] = assignments["split_label"].astype(str).str.strip()
    assignments["cv_fold"] = pd.to_numeric(assignments["cv_fold"], errors="coerce")

    duplicate_ids = assignments["ID_norm"].duplicated(keep=False)
    if duplicate_ids.any():
        examples = assignments.loc[duplicate_ids, "ID_norm"].dropna().head(10).tolist()
        raise ValueError(f"Spatial split assignments contain duplicate IDs; first examples: {examples}")

    return assignments


def apply_spatial_split_assignments(
    model_df: pd.DataFrame,
    assignments: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Attach saved split assignments and return assigned model, train, and test data."""
    required = {"ID_norm", "split_role", "cv_fold", "split_label"}
    missing = required - set(assignments.columns)
    if missing:
        raise ValueError(f"Spatial split assignments are missing columns: {sorted(missing)}")

    keep_cols = ["ID_norm", "split_role", "cv_fold", "split_label"]
    optional_cols = [c for c in ["split_scope", "NUTS3", "municipality_id"] if c in assignments.columns]
    split_cols = assignments[[*keep_cols, *optional_cols]].drop_duplicates("ID_norm").copy()
    rename_cols = {
        "split_role": "spatial_split_role",
        "cv_fold": "spatial_cv_fold",
        "split_label": "spatial_split_label",
    }
    split_cols = split_cols.rename(columns=rename_cols)
    for col in ["NUTS3", "municipality_id"]:
        if col in split_cols.columns:
            split_cols = split_cols.rename(columns={col: f"split_{col}"})

    out = model_df.merge(split_cols, on="ID_norm", how="left", validate="one_to_one")
    missing_ids = out.loc[out["spatial_split_role"].isna(), "ID_norm"].dropna().tolist()
    if missing_ids:
        raise ValueError(
            f"Spatial split assignments are missing {len(missing_ids)} modeling IDs; "
            f"first examples: {missing_ids[:10]}"
        )

    valid_roles = {"training", "fixed_test"}
    bad_roles = sorted(set(out["spatial_split_role"]) - valid_roles)
    if bad_roles:
        raise ValueError(f"Unexpected spatial split roles: {bad_roles}")

    train_df = out.loc[out["spatial_split_role"].eq("training")].copy()
    test_df = out.loc[out["spatial_split_role"].eq("fixed_test")].copy()
    if train_df.empty or test_df.empty:
        raise ValueError(
            f"Saved spatial split failed: train rows={len(train_df)}, test rows={len(test_df)}."
        )

    missing_folds = train_df["spatial_cv_fold"].isna()
    if missing_folds.any():
        examples = train_df.loc[missing_folds, "ID_norm"].head(10).tolist()
        raise ValueError(f"Training rows are missing saved CV folds; first examples: {examples}")

    test_folds = test_df["spatial_cv_fold"].notna()
    if test_folds.any():
        examples = test_df.loc[test_folds, "ID_norm"].head(10).tolist()
        raise ValueError(f"Fixed-test rows unexpectedly have CV folds; first examples: {examples}")

    train_df["spatial_cv_fold"] = train_df["spatial_cv_fold"].astype(int)
    return out, train_df, test_df


def make_precomputed_cv_splits(
    df: pd.DataFrame,
    fold_col: str = "spatial_cv_fold",
    group_col: str = "NUTS3",
) -> tuple[list[tuple[list[int], list[int]]], pd.DataFrame]:
    """Build sklearn CV indices from saved row-level fold assignments."""
    if fold_col not in df.columns:
        raise ValueError(f"Data frame has no saved fold column '{fold_col}'.")

    folds = pd.to_numeric(df[fold_col], errors="coerce")
    if folds.isna().any():
        examples = df.loc[folds.isna(), "ID_norm"].head(10).tolist() if "ID_norm" in df.columns else []
        raise ValueError(f"Saved CV fold column contains missing values; first IDs: {examples}")
    folds = folds.astype(int)

    positions = pd.Series(range(len(df)), index=df.index)
    splits: list[tuple[list[int], list[int]]] = []
    rows = []
    for fold_idx in sorted(folds.unique()):
        is_validation = folds.eq(fold_idx)
        train_idx = positions.loc[~is_validation].tolist()
        validation_idx = positions.loc[is_validation].tolist()
        splits.append((train_idx, validation_idx))

        row = {
            "fold": int(fold_idx),
            "n_rows": len(validation_idx),
        }
        if group_col in df.columns:
            validation_groups = sorted(df.loc[is_validation, group_col].astype(str).unique())
            row["n_nuts3"] = len(validation_groups)
            row["validation_nuts3"] = ", ".join(validation_groups)
        rows.append(row)

    if len(splits) < 2:
        raise ValueError(f"Saved CV split needs at least two folds; found {len(splits)}.")
    return splits, pd.DataFrame(rows)


def rmse(y_true, y_pred) -> float:
    return math.sqrt(mean_squared_error(y_true, y_pred))


def spearman_corr(y_true, y_pred) -> float:
    return pd.Series(y_true).corr(pd.Series(y_pred), method="spearman")
